/**
 * Phase 4 / 4.1 — Historical Projects Excel Mapping & Dry Run.
 *
 * STRICTLY READ-ONLY. This script never calls createHistoricalProjectRequest
 * (the real, write-capable service) and never opens a Prisma transaction
 * that mutates anything — every Prisma call here is a `findMany`/`findUnique`/
 * `count`. Structural validation reuses the REAL, unmodified
 * createHistoricalProjectRequestSchema (lib/validations.ts) via `.safeParse()`
 * only — the exact contract the real privileged route enforces, never a
 * reimplementation of it.
 *
 * ─── Three independent validation stages (Phase 4.1) ───
 *   1. STRUCTURAL — does this source row carry enough well-formed
 *      information to build a valid request payload at all, completely
 *      independent of whether any Department/User/Business Unit name
 *      actually resolves in a real database? Uses PLACEHOLDER ids for
 *      departmentId/ownerIds (any non-empty string satisfies the schema's
 *      own shape rules) so a missing/malformed TITLE, DATE, STATUS, or
 *      missing MANIFEST ENTRY is never masked by, or confused with, a
 *      downstream mapping problem.
 *   2. ORGANIZATIONAL/USER MAPPING — resolves Team/Team's Owner/Project
 *      Owner/Audiences/Responsible People against the REAL database the
 *      script is run against, with confidence scoring. See "PRODUCTION
 *      MODE" below for the rule governing when a resolution is ever
 *      treated as final.
 *   3. FINAL IMPORT ELIGIBILITY — a row is ELIGIBLE only when BOTH of the
 *      above are clean: structurally valid AND every required mapping is
 *      RESOLVED (never merely PENDING_PRODUCTION_VALIDATION).
 *
 * ─── PRODUCTION MODE (--production) ───
 * Without this flag (the default — what THIS session is restricted to;
 * see this feature's own "Do not access or modify the production
 * database"), EVERY mapping outcome is forced to
 * PENDING_PRODUCTION_VALIDATION regardless of confidence — an "EXACT"
 * match against a LOCAL SANDBOX database is NEVER accepted as a
 * production mapping, however confident it looks (this sandbox's local
 * dev DB contains zero real Saracakis Group organizational/user data —
 * confirmed in Phase 4 — only synthetic test fixtures and a handful of
 * generic starter departments that happen to share common names). With
 * `--production` (meant to be run by the Helpdesk owner directly against
 * the real production database, OUTSIDE this session, per this feature's
 * own scope restriction), an EXACT match resolves; FUZZY/AMBIGUOUS/NONE
 * all still require human confirmation
 * (PENDING_PRODUCTION_VALIDATION). "Group"/"CEO" (FORCE_MANUAL_REVIEW) are
 * NEVER auto-resolved in either mode — see this feature's own "Group and
 * CEO audiences require explicit mapping approval."
 *
 * ─── Stable identity (Phase 4.1) ───
 * externalSourceId is never computed inline here — it's looked up from
 * the persistent manifest (scripts/historical-import/manifest.ts,
 * generated by generate-manifest.ts) by natural key. A row with no
 * matching manifest entry is reported as a STRUCTURAL blocker, never
 * assigned an ad hoc id.
 *
 * ─── Reusability ───
 * No hardcoded development ids anywhere in this file — every DB lookup
 * resolves by name against whatever `DATABASE_URL` the process is run
 * with. Re-point this at a different source file and/or the real
 * production database with ZERO code changes:
 *
 *   DATABASE_URL="<production-url>" node --require ./scripts/test-support-server-only-stub.cjs --experimental-test-module-mocks --import tsx scripts/phase4-historical-import-dry-run.ts --production --source="/path/to/export.xlsx"
 *
 * Default (this sandbox, non-production, known source file):
 *   node --require ./scripts/test-support-server-only-stub.cjs --experimental-test-module-mocks --import tsx scripts/phase4-historical-import-dry-run.ts
 */
import fs from "fs/promises";
import path from "path";
import { readProjectListRows, type SourceRow } from "./historical-import/read-source-rows";
import { loadManifest, findManifestEntry } from "./historical-import/manifest";

const DEFAULT_SOURCE_XLSX = "/Users/pavloschatzisavvas/Downloads/ProjectList_ 23-11-2026 (15 10).xlsx";
const DEFAULT_MANIFEST_JSON = path.join(__dirname, "historical-import", "manifests", "project-list-2026-11-23.json");
// Never a repo path by default — this is a generated, run-specific report,
// never a source file to commit. Pass --output= to write it anywhere else.
const DEFAULT_OUTPUT_JSON = path.join(require("os").tmpdir(), "phase4-dry-run-results.json");

function parseArgs() {
  const args = process.argv.slice(2);
  const production = args.includes("--production");
  const source = args.find((a) => a.startsWith("--source="))?.slice("--source=".length) ?? DEFAULT_SOURCE_XLSX;
  const manifestPath = args.find((a) => a.startsWith("--manifest="))?.slice("--manifest=".length) ?? DEFAULT_MANIFEST_JSON;
  const output = args.find((a) => a.startsWith("--output="))?.slice("--output=".length) ?? DEFAULT_OUTPUT_JSON;
  return { production, source, manifestPath, output };
}

const STATUS_MAP: Record<string, string> = {
  Delivered: "COMPLETED",
  "In Progress": "IN_PROGRESS",
  "On Hold": "ON_HOLD",
  Cancelled: "CANCELLED",
};

// Never auto-resolved, no matter what a fuzzy DB search turns up, and
// never accepted even in --production mode without an explicit human
// mapping decision — see this file's own top-level doc comment.
const FORCE_MANUAL_REVIEW = new Set(["Group", "CEO"]);

function splitMulti(v: string | null | undefined): string[] {
  if (!v) return [];
  return v
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
}

function toDateOnly(iso: string | null | undefined): string | null {
  if (!iso) return null;
  return iso.slice(0, 10);
}

type Confidence = "EXACT" | "FUZZY" | "AMBIGUOUS" | "NONE" | "MANUAL_REVIEW";
type MappingStatus = "RESOLVED" | "PENDING_PRODUCTION_VALIDATION";

interface ResolutionResult {
  sourceValue: string;
  entityType: "User" | "Department" | "BusinessUnit" | "Company" | "Unresolved";
  matches: { id: string; name: string | null; email?: string; isActive?: boolean }[];
  confidence: Confidence;
  mappingStatus: MappingStatus;
  note: string;
}

function finalizeMappingStatus(confidence: Confidence, productionMode: boolean): MappingStatus {
  if (confidence === "MANUAL_REVIEW") return "PENDING_PRODUCTION_VALIDATION";
  if (!productionMode) return "PENDING_PRODUCTION_VALIDATION"; // never accept a sandbox/dev entity as a production mapping
  return confidence === "EXACT" ? "RESOLVED" : "PENDING_PRODUCTION_VALIDATION";
}

async function main() {
  const { production, source, manifestPath, output } = parseArgs();

  const { prisma } = await import("@/lib/prisma");
  try {
    await prisma.$connect();
  } catch (err) {
    console.log("No reachable DATABASE_URL.");
    console.log(String(err instanceof Error ? err.message : err));
    process.exit(1);
  }
  const { createHistoricalProjectRequestSchema } = await import("@/lib/validations");

  const rows = await readProjectListRows(source);
  const manifest = await loadManifest(manifestPath);

  // ── Resolution caches (one DB round-trip per unique value, never per row) ──
  const userCache = new Map<string, ResolutionResult>();
  const orgCache = new Map<string, ResolutionResult>();

  async function resolveUser(name: string): Promise<ResolutionResult> {
    const key = name.trim();
    if (userCache.has(key)) return userCache.get(key)!;
    const exact = await prisma.user.findMany({
      where: { name: { equals: key, mode: "insensitive" } },
      select: { id: true, name: true, email: true, isActive: true },
    });
    let confidence: Confidence;
    let matches = exact;
    let note = "";
    if (exact.length === 1) {
      confidence = "EXACT";
    } else if (exact.length > 1) {
      confidence = "AMBIGUOUS";
      note = "Multiple active users share this exact name.";
    } else {
      const firstToken = key.split(/\s+/)[0];
      const fuzzy = await prisma.user.findMany({
        where: { name: { contains: firstToken, mode: "insensitive" } },
        select: { id: true, name: true, email: true, isActive: true },
        take: 5,
      });
      matches = fuzzy;
      if (fuzzy.length) {
        confidence = "FUZZY";
        note = "Partial name match only — requires confirmation.";
      } else {
        confidence = "NONE";
        note = "No active user found by this name in the database this run connected to.";
      }
    }
    const result: ResolutionResult = {
      sourceValue: key,
      entityType: matches.length ? "User" : "Unresolved",
      matches,
      confidence,
      mappingStatus: finalizeMappingStatus(confidence, production),
      note,
    };
    userCache.set(key, result);
    return result;
  }

  async function resolveOrgEntity(name: string): Promise<ResolutionResult> {
    const key = name.trim();
    if (orgCache.has(key)) return orgCache.get(key)!;

    if (FORCE_MANUAL_REVIEW.has(key)) {
      const result: ResolutionResult = {
        sourceValue: key,
        entityType: "Unresolved",
        matches: [],
        confidence: "MANUAL_REVIEW",
        mappingStatus: "PENDING_PRODUCTION_VALIDATION",
        note: `"${key}" is inherently organization-wide/ambiguous in the source data — deliberately NEVER auto-resolved to avoid granting broader access than intended, in EITHER mode. Requires an explicit owner decision on the EXACT Department/Business Unit/Company this should become.`,
      };
      orgCache.set(key, result);
      return result;
    }

    const [deptExact, buExact, companyExact] = await Promise.all([
      prisma.department.findMany({ where: { name: { equals: key, mode: "insensitive" } }, select: { id: true, name: true, isActive: true } }),
      prisma.businessUnit.findMany({ where: { name: { equals: key, mode: "insensitive" } }, select: { id: true, name: true } }),
      prisma.company.findMany({ where: { name: { equals: key, mode: "insensitive" } }, select: { id: true, name: true } }),
    ]);
    const exactMatches = [
      ...deptExact.map((d) => ({ ...d, entityType: "Department" as const })),
      ...buExact.map((b) => ({ ...b, entityType: "BusinessUnit" as const, isActive: undefined })),
      ...companyExact.map((c) => ({ ...c, entityType: "Company" as const, isActive: undefined })),
    ];
    let confidence: Confidence;
    let matches: typeof exactMatches = exactMatches;
    let entityType: ResolutionResult["entityType"] = exactMatches[0]?.entityType ?? "Unresolved";
    let note = "";
    if (exactMatches.length === 1) {
      confidence = "EXACT";
    } else if (exactMatches.length > 1) {
      confidence = "AMBIGUOUS";
      note = "Multiple entities (possibly across Department/Business Unit/Company) share this exact name.";
    } else {
      const [deptFuzzy, buFuzzy] = await Promise.all([
        prisma.department.findMany({ where: { name: { contains: key.split(/[\s&-]+/)[0], mode: "insensitive" } }, select: { id: true, name: true, isActive: true }, take: 5 }),
        prisma.businessUnit.findMany({ where: { name: { contains: key.split(/[\s&-]+/)[0], mode: "insensitive" } }, select: { id: true, name: true }, take: 5 }),
      ]);
      const fuzzy = [...deptFuzzy.map((d) => ({ ...d, entityType: "Department" as const })), ...buFuzzy.map((b) => ({ ...b, entityType: "BusinessUnit" as const, isActive: undefined }))];
      matches = fuzzy;
      entityType = fuzzy[0]?.entityType ?? "Unresolved";
      if (fuzzy.length) {
        confidence = "FUZZY";
        note = "Partial name match only — requires confirmation.";
      } else {
        confidence = "NONE";
        note = "No Department, Business Unit or Company found by this name in the database this run connected to.";
      }
    }
    const result: ResolutionResult = {
      sourceValue: key,
      entityType,
      matches,
      confidence,
      mappingStatus: finalizeMappingStatus(confidence, production),
      note,
    };
    orgCache.set(key, result);
    return result;
  }

  // ── Per-project dry run ──
  const projectResults: any[] = [];
  let structuralPassCount = 0;
  let eligibleCount = 0;

  for (const row of rows) {
    const manifestEntry = findManifestEntry(manifest, row);
    const structuralIssues: string[] = [];
    if (!manifestEntry) {
      structuralIssues.push(`No manifest entry found for this row — run scripts/historical-import/generate-manifest.ts against the current source file first.`);
    }

    // ── Stage 1: STRUCTURAL — placeholder ids stand in for department/
    // owner so a schema failure here can ONLY be a genuine structural
    // problem (title/date/status shape), never a mapping problem. ──
    const feedbackUsers = row.feedbackUsers;
    const estimatedCost = row.estimatedCost;
    const actualCost = row.actualCost;
    const totalDays = row.totalDays;
    const hasAnyMetadata = feedbackUsers != null || estimatedCost != null || actualCost != null || totalDays != null;

    const structuralPayload = {
      title: row.title,
      description: row.description ?? undefined,
      // importance/teamConcerned/expectedBenefits: no source column at all
      // (see Phase 4.1's own "Historical field validation") — never
      // guessed, always omitted here exactly as the real import would.
      externalSourceId: manifestEntry?.externalSourceId ?? "PLACEHOLDER__no-manifest-entry",
      departmentId: "placeholder-department-id",
      projectStatus: STATUS_MAP[row.status ?? ""] ?? undefined,
      startDate: toDateOnly(row.actualStartDate),
      endDate: toDateOnly(row.actualFinishDate),
      expectedStartDate: toDateOnly(row.expectedStartDate),
      expectedFinishDate: toDateOnly(row.expectedFinishDate),
      ownerIds: ["placeholder-owner-id"],
      historicalSourceMetadata: hasAnyMetadata
        ? {
            feedbackUsers: feedbackUsers ?? undefined,
            originalEstimatedCost: typeof estimatedCost === "number" ? estimatedCost : undefined,
            originalActualCost: typeof actualCost === "number" ? actualCost : undefined,
            originalTotalDays: typeof totalDays === "number" ? totalDays : undefined,
          }
        : undefined,
    };
    const zodResult = createHistoricalProjectRequestSchema.safeParse(structuralPayload);
    if (!zodResult.success) {
      for (const issue of zodResult.error.issues) structuralIssues.push(`${issue.path.join(".")}: ${issue.message}`);
    }
    if (!STATUS_MAP[row.status ?? ""]) structuralIssues.push(`Source Status "${row.status}" has no mapped canonical ProjectStatus.`);
    const stage1 = structuralIssues.length === 0 ? "STRUCTURAL_VALID" : "STRUCTURAL_INVALID";
    if (stage1 === "STRUCTURAL_VALID") structuralPassCount++;

    // ── Stage 2: Organizational/user mapping ──
    const teamRes = row.team ? await resolveOrgEntity(row.team) : null;
    const requesterDeptRes = row.projectOwner ? await resolveOrgEntity(row.projectOwner) : null;
    const ownerRes = row.teamsOwner ? await resolveUser(row.teamsOwner) : null;
    const audienceTokens = splitMulti(row.audiences);
    const audienceResolutions = await Promise.all(audienceTokens.map((t) => resolveOrgEntity(t)));
    const responsibleTokens = splitMulti(row.responsiblePeople);
    const responsibleResolutions = await Promise.all(responsibleTokens.map((t) => resolveUser(t)));

    const pendingMappings: string[] = [];
    if (!teamRes || teamRes.mappingStatus === "PENDING_PRODUCTION_VALIDATION") {
      pendingMappings.push(`Project Department ("${row.team}") — ${teamRes?.note || "requires production validation"}.`);
    }
    if (!ownerRes || ownerRes.mappingStatus === "PENDING_PRODUCTION_VALIDATION") {
      pendingMappings.push(`Project Owner/User ("${row.teamsOwner}") — ${ownerRes?.note || "requires production validation"}.`);
    }
    if (requesterDeptRes && requesterDeptRes.mappingStatus === "PENDING_PRODUCTION_VALIDATION") {
      pendingMappings.push(`Requester Department ("${row.projectOwner}") — ${requesterDeptRes.note || "requires production validation"}.`);
    }
    audienceResolutions.forEach((r, i) => {
      if (r.mappingStatus === "PENDING_PRODUCTION_VALIDATION") pendingMappings.push(`Audience ("${audienceTokens[i]}") — ${r.note || "requires production validation"}.`);
    });
    responsibleResolutions.forEach((r, i) => {
      if (r.mappingStatus === "PENDING_PRODUCTION_VALIDATION") pendingMappings.push(`Responsible Person ("${responsibleTokens[i]}") — ${r.note || "requires production validation"}.`);
    });
    const stage2 = pendingMappings.length === 0 ? "ALL_MAPPINGS_RESOLVED" : "PENDING_PRODUCTION_VALIDATION";

    // ── Stage 3: FINAL IMPORT ELIGIBILITY ──
    const eligible = stage1 === "STRUCTURAL_VALID" && stage2 === "ALL_MAPPINGS_RESOLVED";
    if (eligible) eligibleCount++;

    projectResults.push({
      excelRow: row.excelRow,
      title: row.title,
      ticketId: row.ticketId, // out of scope for import — shown here for human cross-reference only
      zohoLink: row.zohoLink, // out of scope for import — shown here for human cross-reference only
      externalSourceId: manifestEntry?.externalSourceId ?? null,
      status: row.status,
      mappedProjectStatus: STATUS_MAP[row.status ?? ""] ?? null,
      team: row.team,
      teamResolution: teamRes,
      teamsOwnerRaw: row.teamsOwner,
      ownerResolution: ownerRes,
      projectOwnerColRaw: row.projectOwner,
      requesterDepartmentResolution: requesterDeptRes,
      audienceTokens,
      audienceResolutions,
      responsiblePeopleTokens: responsibleTokens,
      responsibleResolutions,
      actualStartDate: toDateOnly(row.actualStartDate),
      actualFinishDate: toDateOnly(row.actualFinishDate),
      expectedStartDate: toDateOnly(row.expectedStartDate),
      expectedFinishDate: toDateOnly(row.expectedFinishDate),
      totalDaysSource: row.totalDays, // preserved as historicalSourceMetadata.originalTotalDays — never mapped to Expected/Actual Days, see this file's own doc comment
      feedbackUsersSource: row.feedbackUsers,
      estimatedCostSource: row.estimatedCost,
      actualCostSource: row.actualCost,
      description: row.description,
      stage1Structural: stage1,
      structuralIssues,
      stage2Mapping: stage2,
      pendingMappings,
      stage3Eligibility: eligible ? "ELIGIBLE" : "BLOCKED",
    });
  }

  // ── Duplicate/existing-record check (read-only) ──
  const candidateIds = projectResults.map((r) => r.externalSourceId).filter((id): id is string => !!id);
  const existingByExternalId = await prisma.projectRequest.findMany({
    where: { externalSourceId: { in: candidateIds } },
    select: { id: true, externalSourceId: true, title: true },
  });
  const existingByTitle = await prisma.projectRequest.findMany({
    where: { title: { in: rows.map((r) => r.title) } },
    select: { id: true, title: true, externalSourceId: true, source: true },
  });

  // ── Unique-value inventories for the User/Organizational Mapping sheets ──
  const allUserNames = new Set<string>();
  const allOrgNames = new Set<string>();
  for (const row of rows) {
    if (row.teamsOwner) allUserNames.add(row.teamsOwner);
    for (const n of splitMulti(row.responsiblePeople)) allUserNames.add(n);
    if (row.team) allOrgNames.add(row.team);
    if (row.projectOwner) allOrgNames.add(row.projectOwner);
    for (const n of splitMulti(row.audiences)) allOrgNames.add(n);
  }
  const userMappingTable = await Promise.all(Array.from(allUserNames).map((n) => resolveUser(n)));
  const orgMappingTable = await Promise.all(Array.from(allOrgNames).map((n) => resolveOrgEntity(n)));

  const result = {
    generatedAt: new Date().toISOString(),
    productionMode: production,
    sourceFile: source,
    manifestFile: manifestPath,
    dataSourceCaveat: production
      ? "Run WITH --production: EXACT matches are treated as resolved. Still verify the database this connected to is really the intended one — this script trusts DATABASE_URL, nothing else."
      : "Run WITHOUT --production (the default/sandbox mode): EVERY organizational/user mapping is forced to PENDING_PRODUCTION_VALIDATION regardless of confidence, even an 'EXACT' match — this sandbox's local dev database has ZERO real Saracakis Group organizational/user data (confirmed in Phase 4), so no mapping found here may ever be treated as a real production mapping. This run exists to prove the MECHANISM and Stage 1 structural validation only.",
    exclusions: "Ticket ID and Zoho Link are explicitly OUT OF SCOPE for import — never written to any payload, never stored in historicalSourceMetadata. Shown in this report for human cross-reference only.",
    totalProjects: rows.length,
    structuralPassCount,
    eligibleCount,
    projectResults,
    userMappingTable,
    orgMappingTable,
    existingByExternalId,
    existingByTitle,
  };
  await fs.writeFile(output, JSON.stringify(result, null, 2), "utf8");
  console.log(`Wrote dry-run results for ${rows.length} projects to ${output}`);
  console.log(`Mode: ${production ? "PRODUCTION" : "SANDBOX (default)"}`);
  console.log(`Stage 1 (structural) passed: ${structuralPassCount}/${rows.length}`);
  console.log(`Stage 3 (final eligibility): ${eligibleCount}/${rows.length} ELIGIBLE`);
  console.log(`Existing ProjectRequest rows matching any candidate externalSourceId: ${existingByExternalId.length} (expected 0)`);
  console.log(`Existing ProjectRequest rows matching any source Title: ${existingByTitle.length} (expected 0)`);

  await prisma.$disconnect();
}

main().catch((err) => {
  console.error("Dry run failed:", err);
  process.exit(1);
});
